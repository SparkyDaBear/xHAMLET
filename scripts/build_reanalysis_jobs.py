#!/usr/bin/env python3
"""Generate chunked Slurm jobs to reprocess many PXDs through the main xHAMLET pipeline.

Unlike scripts/build_af3_ppi_jobs.py (one job per AF3 structure prediction,
each needing a GPU), this generator batches many PXDs per Slurm job: each PXD
here is a lightweight, CPU-only run through src/main.py (PRIDE/publication
fetch + LLM extraction + SDRF + Xi config, no raw-file download, no ReLink),
so one-PXD-per-job would mean excessive scheduling overhead for the work
involved. Batching into modest chunks instead gives parallelism across the
cluster while keeping failures isolated and cheaply resumable per chunk
(just resubmit the one failed chunk, not the whole run).

For each chunk this writes:
  <out-dir>/chunk_<NNN>.tsv    - the chunk's PXD accessions (Accession column)
  <out-dir>/chunk_<NNN>.slurm  - ready-to-submit Slurm script
plus a manifest.tsv and a submit_all.sh helper that sbatches every chunk.

Examples:
    python scripts/build_reanalysis_jobs.py
    python scripts/build_reanalysis_jobs.py --pxd-file assets/crosslinking_datasets_list.tsv --chunk-size 25
    python scripts/build_reanalysis_jobs.py --out-dir reanalysis_jobs --submit
"""

from __future__ import annotations

import argparse
import subprocess
from pathlib import Path

import pandas as pd

DEFAULT_PXD_FILE = Path("assets/crosslinking_datasets_list.tsv")
DEFAULT_OUT_DIR = Path("reanalysis_jobs")

SLURM_TEMPLATE = """#!/usr/bin/env bash
#SBATCH --job-name=xhamlet_reanalysis_{chunk_name}
#SBATCH --partition={partition}
{account_line}#SBATCH --ntasks={ntasks}
#SBATCH --mem={mem}
#SBATCH --time={time}
#SBATCH --output={out_dir}/{chunk_name}_%j.out

# Auto-generated by scripts/build_reanalysis_jobs.py - one chunk of PXDs, one job.
set -euo pipefail

CONDA_BASE=/storage/group/epo2/default/ims86/miniconda3
export NXF_HOME=/storage/group/epo2/default/ims86/.nextflow

cd {repo_root}

source "${{CONDA_BASE}}/etc/profile.d/conda.sh"
conda activate xhamlet

echo "Reanalyzing chunk {chunk_name}: {pxd_count} PXDs"
python src/main.py \\
  --pxd-file "{chunk_tsv}" \\
  --config "{config_path}" \\
  --data-dir "{data_dir}" \\
  {force_refresh_flag}--no-download \\
  --log-file "{out_dir}/{chunk_name}.log"

echo "Done: {chunk_name}"
"""


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--pxd-file", type=Path, default=DEFAULT_PXD_FILE, help="TSV with an 'Accession' column (default: %(default)s)")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR, help="Output directory for chunk TSVs/Slurm scripts")
    parser.add_argument("--config", type=Path, default=Path("configs/config.yaml"), help="xHAMLET config.yaml")
    parser.add_argument("--data-dir", default="store", help="Result store root (default: %(default)s)")
    parser.add_argument("--chunk-size", type=int, default=25, help="PXDs per Slurm job (default: %(default)s)")
    parser.add_argument("--partition", default="basic", help="Slurm partition (default: %(default)s)")
    parser.add_argument("--account", default="ncems_cr_default", help="Optional Slurm --account")
    parser.add_argument("--ntasks", type=int, default=4, help="Slurm --ntasks per chunk job (default: %(default)s)")
    parser.add_argument("--mem", default="16G", help="Slurm --mem per chunk job (default: %(default)s)")
    parser.add_argument("--time", default="12:00:00", help="Slurm --time per chunk job (default: %(default)s)")
    parser.add_argument("--submit", action="store_true", help="Immediately sbatch every generated chunk instead of just writing scripts")
    parser.add_argument("--dry-run", action="store_true", help="Report planned chunks without writing files")
    parser.add_argument(
        "--no-force-refresh",
        action="store_true",
        help="Omit --force-refresh so each stage reuses its own cached output (PRIDE/PMC/LLM/clustering) "
             "when present and only regenerates SDRF + Xi configs (Stages 6 and 8, which always rebuild "
             "regardless of caching). Much cheaper than a full reanalysis: use this to pick up a Xi-config-"
             "generation code fix across already-processed PXDs without re-querying the LLM.",
    )
    return parser.parse_args()


def load_pxds(path: Path) -> list[str]:
    df = pd.read_csv(path, sep="\t", comment="#")
    col_map = {c.lower(): c for c in df.columns}
    if "accession" not in col_map:
        raise ValueError(f"TSV file '{path}' has no 'Accession' column. Found: {list(df.columns)}")
    accession_col = col_map["accession"]
    pxds = df[accession_col].dropna().astype(str).str.strip()
    pxds = pxds[pxds.str.startswith("PXD")]
    return pxds.unique().tolist()


def chunked(items: list[str], size: int) -> list[list[str]]:
    return [items[i : i + size] for i in range(0, len(items), size)]


def main() -> int:
    args = parse_args()
    repo_root = Path(__file__).resolve().parents[1]

    pxds = load_pxds(args.pxd_file)
    chunks = chunked(pxds, args.chunk_size)
    print(f"Loaded {len(pxds)} PXDs from {args.pxd_file}; split into {len(chunks)} chunk(s) of up to {args.chunk_size}.")

    if args.dry_run:
        for i, chunk in enumerate(chunks, start=1):
            print(f"  chunk_{i:03d}: {len(chunk)} PXDs ({chunk[0]}..{chunk[-1]})")
        print("Dry run: no files written.")
        return 0

    args.out_dir.mkdir(parents=True, exist_ok=True)
    account_line = f"#SBATCH --account={args.account}\n" if args.account else ""

    manifest_rows = ["chunk_name\tpxd_count\ttsv_path\tslurm_path\tstatus"]
    submit_lines = ["#!/usr/bin/env bash", "set -euo pipefail"]

    for i, chunk in enumerate(chunks, start=1):
        chunk_name = f"chunk_{i:03d}"
        chunk_tsv = args.out_dir / f"{chunk_name}.tsv"
        chunk_slurm = args.out_dir / f"{chunk_name}.slurm"

        chunk_tsv.write_text("Accession\n" + "\n".join(chunk) + "\n")

        script = SLURM_TEMPLATE.format(
            chunk_name=chunk_name,
            partition=args.partition,
            account_line=account_line,
            ntasks=args.ntasks,
            mem=args.mem,
            time=args.time,
            repo_root=repo_root,
            chunk_tsv=chunk_tsv.resolve(),
            config_path=args.config.resolve(),
            data_dir=args.data_dir,
            out_dir=args.out_dir.resolve(),
            pxd_count=len(chunk),
            force_refresh_flag="" if args.no_force_refresh else "--force-refresh \\\n  ",
        )
        chunk_slurm.write_text(script)
        chunk_slurm.chmod(0o755)

        manifest_rows.append(f"{chunk_name}\t{len(chunk)}\t{chunk_tsv}\t{chunk_slurm}\tready")
        submit_lines.append(f'sbatch "{chunk_slurm.resolve()}"')

    (args.out_dir / "manifest.tsv").write_text("\n".join(manifest_rows) + "\n")
    submit_all_path = args.out_dir / "submit_all.sh"
    submit_all_path.write_text("\n".join(submit_lines) + "\n")
    submit_all_path.chmod(0o755)

    print(f"Wrote {len(chunks)} chunk TSV/Slurm pairs, manifest.tsv, and submit_all.sh under {args.out_dir}/")

    if args.submit:
        print("Submitting all chunks now (--submit)...")
        subprocess.run(["bash", str(submit_all_path)], check=True)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
